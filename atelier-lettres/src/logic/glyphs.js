// Gabarits de lettres. Boîte [0,1]x[0,1], y vers le bas.
// Un gabarit = traits dans l'ordre d'écriture ; un trait = points dans le sens du tracé.

export function line(x0, y0, x1, y1, n = 10) {
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    pts.push({ x: x0 + (x1 - x0) * t, y: y0 + (y1 - y0) * t });
  }
  return pts;
}

// Angles en degrés, repère écran (y vers le bas) : 0 = droite, 90 = bas, -90 = haut.
// Angle décroissant = sens anti-horaire à l'écran.
export function arc(cx, cy, rx, ry, a0, a1, n) {
  const steps = n || Math.max(8, Math.ceil(Math.abs(a1 - a0) / 10));
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + (a1 - a0) * (i / steps)) * Math.PI) / 180;
    pts.push({ x: cx + rx * Math.cos(a), y: cy + ry * Math.sin(a) });
  }
  return pts;
}

export function concat(...segs) {
  const out = [];
  for (const seg of segs) {
    for (const p of seg) {
      const last = out[out.length - 1];
      if (last && Math.hypot(last.x - p.x, last.y - p.y) < 1e-6) continue;
      out.push({ x: p.x, y: p.y });
    }
  }
  return out;
}

