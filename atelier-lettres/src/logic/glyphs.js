function build(table) {
  const out = {};
  for (const [ch, strokes] of Object.entries(table)) out[ch] = { char: ch, strokes };
  return out;
}

export const GLYPHS = { caps: build(caps), script: build(script), cursive: build(cursive) };
export const STYLES = ['caps', 'script', 'cursive'];

export function getGlyph(style, char) {
  const t = GLYPHS[style];
  if (!t || !char) return null;
  return t[char] || null;
}

