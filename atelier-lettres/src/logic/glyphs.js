// Courbe lisse (Catmull-Rom) passant par les points de contrôle [[x,y],...].
function smooth(ctrl, per = 8) {
  const P = ctrl.map(([x, y]) => ({ x, y }));
  const g = (i) => P[Math.min(P.length - 1, Math.max(0, i))];
  const out = [];
  for (let i = 0; i < P.length - 1; i++) {
    const [p0, p1, p2, p3] = [g(i - 1), g(i), g(i + 1), g(i + 2)];
    for (let k = 0; k < per; k++) {
      const t = k / per;
      const t2 = t * t;
      const t3 = t2 * t;
      const f = (a, b, c, d) => 0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t3);
      out.push({ x: f(p0.x, p1.x, p2.x, p3.x), y: f(p0.y, p1.y, p2.y, p3.y) });
    }
  }
  out.push(P[P.length - 1]);
  return out;
}

